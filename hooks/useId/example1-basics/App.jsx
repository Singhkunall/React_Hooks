/**
 * @fileoverview Example 1 — Basics of useId
 * Demonstrates how React's useId() hook generates a unique, stable ID
 * per component instance to link <label> elements to <input> elements
 * for accessibility and click-to-focus behavior, with interactive feedback.
 */
import { useId, useState } from 'react'; // Import useId for unique IDs and useState for interactive feedback
function TextField({ label, placeholder }) { // Reusable input component receiving label and placeholder props
  const id = useId(); // Generate a unique, stable ID string (e.g. ":r0:") for this component instance
  const [value, setValue] = useState(''); // Track the current text entered into this specific input
  const [focused, setFocused] = useState(false); // Track whether this input currently has focus
  return ( // Return the labeled input UI for this field
    <div style={{ marginBottom: '16px' }}> {/* Outer wrapper spacing each field vertically */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '4px' }}> {/* Header row for label and ID badge */}
        <label // Accessible label element linked to the input below
          htmlFor={id} // Match the input's id so clicking the label focuses the input
          style={{ fontWeight: 'bold', cursor: 'pointer', color: focused ? '#4f46e5' : '#111827' }} // Highlight label when its input is focused
        > {/* Close opening label tag */}
          {label} {/* Render the label text passed via props */}
        </label> {/* Close label element */}
        <code style={{ fontSize: '12px', backgroundColor: '#e0f2fe', color: '#0369a1', padding: '2px 6px', borderRadius: '4px' }}> {/* Badge displaying the generated ID */}
          id=&quot;{id}&quot; {/* Show the actual useId() value for learning visibility */}
        </code> {/* Close code badge */}
      </div> {/* Close header row */}
      <input // Controlled text input element
        id={id} // Assign the unique ID generated by useId()
        type="text" // Standard single-line text input
        value={value} // Bind input value to React state
        placeholder={placeholder} // Show helpful hint text when empty
        onChange={(e) => setValue(e.target.value)} // Update state whenever the user types
        onFocus={() => setFocused(true)} // Mark field as focused for visual feedback
        onBlur={() => setFocused(false)} // Clear focused state when focus leaves
        style={{ // Inline styling for the input box
          width: '100%', // Span full container width
          boxSizing: 'border-box', // Include padding and border in width calculation
          border: `2px solid ${focused ? '#4f46e5' : '#d1d5db'}`, // Highlight border when focused
          borderRadius: '6px', // Slightly rounded corners
          padding: '8px 12px', // Comfortable inner padding
          fontSize: '15px', // Readable text size
          outline: 'none', // Use custom border instead of default focus ring
        }} // End style object
      /> {/* Close self-closing input element */}
    </div> // Close outer wrapper div
  ); // End return statement
} // End TextField component
function App() { // Top-level component rendering multiple TextField instances
  const [showExtra, setShowExtra] = useState(false); // Toggle state to mount/unmount an extra field dynamically
  return ( // Return the main application UI
    <div style={{ padding: '32px', maxWidth: '440px', margin: '0 auto', fontFamily: 'sans-serif' }}> {/* Centered page container */}
      <h1 style={{ marginBottom: '8px', fontSize: '24px' }}>useId — Basic Example</h1> {/* Main page heading */}
      <p style={{ marginBottom: '20px', color: '#4b5563', fontSize: '14px' }}> {/* Helper instructions for the learner */}
        Click any label below — the cursor jumps to its matching input because each instance gets its own unique ID. {/* Explain click-to-focus accessibility */}
      </p> {/* Close paragraph */}
      <TextField label="First Name" placeholder="e.g. Ada" /> {/* First instance gets its own unique ID */}
      <TextField label="Last Name" placeholder="e.g. Lovelace" /> {/* Second instance gets a different unique ID */}
      <TextField label="Email Address" placeholder="e.g. ada@example.com" /> {/* Third instance gets another unique ID */}
      {showExtra && <TextField label="Nickname (Dynamic)" placeholder="e.g. Countess of Lovelace" />} {/* Conditionally render a fourth instance */}
      <button // Interactive button to toggle the extra field
        type="button" // Prevent accidental form submission
        onClick={() => setShowExtra((prev) => !prev)} // Flip showExtra boolean on click
        style={{ // Style the toggle button
          marginTop: '8px', // Space above the button
          padding: '8px 14px', // Button inner spacing
          backgroundColor: '#4f46e5', // Indigo button background
          color: '#ffffff', // White button text
          border: 'none', // Remove default border
          borderRadius: '6px', // Rounded button corners
          cursor: 'pointer', // Pointer cursor on hover
          fontSize: '14px', // Readable button text
        }} // End button style object
      > {/* Close opening button tag */}
        {showExtra ? 'Hide Extra Field' : 'Add Extra Field'} {/* Dynamic button label based on state */}
      </button> {/* Close button element */}
      <div style={{ marginTop: '20px', padding: '14px', backgroundColor: '#f0f9ff', border: '1px solid #bae6fd', borderRadius: '8px', fontSize: '13px' }}> {/* Info callout box */}
        <strong>What&apos;s happening:</strong> Each <code>&lt;TextField&gt;</code> calls <code>useId()</code> once and receives a stable, collision-free ID. {/* Summarize the core lesson */}
      </div> {/* Close info callout box */}
    </div> // Close main container
  ); // End App return
} // End App component
export default App; // Export App as default for the React entry point
